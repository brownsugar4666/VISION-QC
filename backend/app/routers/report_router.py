def _generate_pdf_bytes(batch, inspections, plant, line, shift, part_type, defect_types_map, session):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image
    from reportlab.lib.styles import getSampleStyleSheet

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("VisionQC Defect Report", styles["Title"]))
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(f"Plant: {plant.name} — {plant.location}", styles["Normal"]))
    elements.append(Paragraph(f"Line: {line.name} | Shift: {shift.name} | Part: {part_type.name}", styles["Normal"]))
    elements.append(Paragraph(f"Date: {batch.created_at.strftime('%d %b %Y, %H:%M IST')}", styles["Normal"]))
    elements.append(Spacer(1, 15))

    total = len(inspections)
    passed = sum(1 for i in inspections if i.result == "ok")
    defective = sum(1 for i in inspections if i.result == "defective")
    rate = round(defective / total * 100, 1) if total > 0 else 0

    summary_data = [
        ["Metric", "Value"],
        ["Total Images", str(total)],
        ["Passed (OK)", str(passed)],
        ["Defective", str(defective)],
        ["Defect Rate", f"{rate}%"],
    ]
    t = Table(summary_data, colWidths=[200, 200])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a365d")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ALIGN", (1, 0), (1, -1), "CENTER"),
    ]))
    elements.append(t)
    elements.append(Spacer(1, 15))

    defect_counts = {}
    for insp in inspections:
        if insp.result == "defective" and insp.defect_type_id:
            dname = defect_types_map.get(insp.defect_type_id, "Unknown")
            defect_counts[dname] = defect_counts.get(dname, 0) + 1

    if defect_counts:
        elements.append(Paragraph("Defects by Type", styles["Heading2"]))
        dtype_data = [["Defect Type", "Count"]]
        for dname, count in sorted(defect_counts.items(), key=lambda x: -x[1]):
            dtype_data.append([dname, str(count)])
        t2 = Table(dtype_data, colWidths=[200, 200])
        t2.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2d3748")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ]))
        elements.append(t2)
        elements.append(Spacer(1, 15))

    defective_inspections = [i for i in inspections if i.result == "defective"][:6]
    if defective_inspections:
        elements.append(Paragraph("Sample Defective Images", styles["Heading2"]))
        for insp in defective_inspections:
            base_dir = os.path.join(os.path.dirname(__file__), "..", "..", "..")
            img_path = os.path.join(base_dir, insp.image_path)
            if os.path.exists(img_path):
                try:
                    img = Image(img_path, width=120, height=120)
                    dt_name = defect_types_map.get(insp.defect_type_id, "Unknown") if insp.defect_type_id else "Unknown"
                    elements.append(Paragraph(f"ID #{insp.id} — {dt_name} (confidence: {insp.confidence:.0%})", styles["Normal"]))
                    elements.append(img)
                    elements.append(Spacer(1, 8))
                except Exception:
                    pass

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("Generated by VisionQC — AI Visual Quality Inspection", styles["Italic"]))

    doc.build(elements)
    buf.seek(0)
    return buf


@router.get("/batch/{batch_id}/pdf")
def batch_pdf_report(batch_id: int, session: Session = Depends(get_session), user: User = Depends(get_current_user)):
    batch = session.get(Batch, batch_id)
    if not batch:
        raise HTTPException(status_code=404, detail="Batch not found")

    inspections = session.exec(select(Inspection).where(Inspection.batch_id == batch_id)).all()
    plant = session.get(Plant, batch.plant_id)
    line = session.get(Line, batch.line_id)
    shift = session.get(Shift, batch.shift_id)
    part_type = session.get(PartType, batch.part_type_id)

    defect_types = session.exec(select(DefectType).where(DefectType.plant_id == batch.plant_id)).all()
    defect_types_map = {dt.id: dt.name for dt in defect_types}

    buf = _generate_pdf_bytes(batch, inspections, plant, line, shift, part_type, defect_types_map, session)

    return StreamingResponse(
        buf,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename=visionqc_batch_{batch_id}_report.pdf"},
    )


@router.get("/batch/{batch_id}/whatsapp")
def whatsapp_message(batch_id: int, session: Session = Depends(get_session), user: User = Depends(get_current_user)):
    batch = session.get(Batch, batch_id)
    if not batch:
        raise HTTPException(status_code=404, detail="Batch not found")

    plant = session.get(Plant, batch.plant_id)
    line = session.get(Line, batch.line_id)
    shift = session.get(Shift, batch.shift_id)
    part_type = session.get(PartType, batch.part_type_id)

    total = batch.total_images
    defective = batch.defective_count
    rate = round(defective / total * 100, 1) if total > 0 else 0

    message = (
        f"📋 *VisionQC Defect Report*\n"
        f"Plant: {plant.name}\n"
        f"Line: {line.name} | Shift: {shift.name}\n"
        f"Part: {part_type.name}\n"
        f"Date: {batch.created_at.strftime('%d %b %Y')}\n\n"
        f"✅ Passed: {batch.passed_count}/{total}\n"
        f"❌ Defective: {defective}/{total}\n"
        f"📊 Defect Rate: {rate}%\n\n"
        f"View full report in VisionQC dashboard."
    )

    wa_link = f"https://wa.me/?text={urllib.parse.quote(message)}"

    return {
        "message": message,
        "whatsapp_link": wa_link,
    }
